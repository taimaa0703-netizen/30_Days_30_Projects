export function translate(language, text) {
  const translated = translations[language]?.[text] || text;
  if (language !== 'ar') return translated;
  return translated.replace(/\{[^}]+\}|[A-Za-z][A-Za-z0-9]*(?:[._/@:+-][A-Za-z0-9]+)*/g, token =>
    token.startsWith('{') ? token : `\u2066${token}\u2069`
  );
}

export function fillTemplate(template, values) {
  return template.replace(/\{(\w+)\}/g, (_, key) => values[key] ?? '');
}

export function localizeInsight(language, insight) {
  const title = translate(language, insight.title);
  let description = insight.description;
  let match;

  if (language === 'he' && insight.title === 'Low lead quality') {
    match = description.match(/Only (.+) of (\d+) leads reached qualified or won status\./);
    if (match) description = fillTemplate(translate(language, 'Only {rate} of {count} leads reached qualified or won status. Review targeting, ad promise and lead form.'), {rate: match[1], count: match[2]});
  } else if (language === 'ar' && insight.title === 'Low lead quality') {
    match = description.match(/Only (.+) of (\d+) leads reached qualified or won status\./);
    if (match) description = fillTemplate(translate(language, 'Only {rate} of {count} leads reached qualified or won status. Review targeting, ad promise and lead form.'), {rate: match[1], count: match[2]});
  } else if ((language === 'he' || language === 'ar') && insight.title === 'Slow lead follow-up') {
    match = description.match(/Average first response is (\d+) minutes\./);
    if (match) description = fillTemplate(translate(language, 'Average first response is {minutes} minutes. Check sales coverage before attributing weak outcomes to the ads.'), {minutes: match[1]});
  } else if ((language === 'he' || language === 'ar') && insight.title === 'Strong observed revenue') {
    match = description.match(/Observed ROAS is ([\d.]+)x across (\d+) won leads\./);
    if (match) description = fillTemplate(translate(language, 'Observed ROAS is {roas}x across {won} won leads. Validate CRM attribution and capacity before raising budget.'), {roas: match[1], won: match[2]});
  } else if ((language === 'he' || language === 'ar') && insight.title === 'Leads without closed sales') {
    match = description.match(/^(\d+) leads are associated with this campaign but none are marked won in the imported CRM data\.$/);
    if (match) description = fillTemplate(translate(language, '{count} leads are associated with this campaign but none are marked won in the imported CRM data.'), {count: match[1]});
  } else if ((language === 'he' || language === 'ar') && insight.title === 'Missing CRM attribution') {
    match = description.match(/^(\d+) imported leads do not match a campaign ID\.$/);
    if (match) description = fillTemplate(translate(language, '{count} imported leads do not match a campaign ID.'), {count: match[1]});
  }

  return {
    ...insight,
    title,
    description: translate(language, description),
    hypotheses: translate(language, insight.hypotheses || ''),
    action: translate(language, insight.action)
  };
}
